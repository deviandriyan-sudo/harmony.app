import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (name) => readFileSync(new URL(`../${name}`, import.meta.url), 'utf8')
const layout = read('app/layout.tsx')
const bridge = read('components/ui/HarmonyModalFeedbackLayer.tsx')
const css = read('app/globals.css')
const modal = read('components/ui/HarmonyModalPortal.tsx')
const attendance = read('app/employee/attendance/page.tsx')
const hrLeave = read('app/hr/leave/page.tsx')

assert(layout.includes('<HarmonyModalFeedbackLayer />'), 'Feedback bridge must mount globally at the root')
assert(layout.includes('<SystemMaintenanceGate>{children}</SystemMaintenanceGate>'), 'Keep maintenance gate')
assert(bridge.includes('MutationObserver'), 'Page alerts must be discovered after async submissions')
assert(bridge.includes('characterData: true'), 'Changed message text must be observed')
assert(bridge.includes('attributes: true'), 'Visibility and feedback changes must be observed')
assert(bridge.includes('createPortal(') && bridge.includes('feedback.modal'), 'Feedback must be portaled into the active dialog')
assert(bridge.includes("element.closest(MODAL_SELECTOR)"), 'Do not re-broadcast alerts already inside a dialog')
assert(bridge.includes('data-harmony-feedback-relayed'), 'Duplicate page-level toast needs an active suppression state')
assert(bridge.includes("mutation.target instanceof Element"), 'Prevent observer recursion from the feedback portal')
assert(bridge.includes('setDismissed(feedback)'), 'Toast should be dismissible')
assert(bridge.includes("/tutup|close|dismiss/i"), 'Close should invoke the original banner close control when available')
assert(modal.includes('onKeyDown={handleKeyDown}'), 'Keep dialog focus trap')
assert(modal.includes('createPortal(') && modal.includes('document.body'), 'Keep body portal')
assert(attendance.includes('data-harmony-feedback="error"'), 'Attendance errors must remain connected to the bridge')
assert(hrLeave.includes('data-harmony-feedback="error"'), 'HR leave errors must remain connected to the bridge')
for (const page of [attendance, hrLeave]) assert(page.includes('data-harmony-feedback="success"'), 'Success banners must have a semantic marker')
assert(css.includes('z-index: 2600 !important;'), 'Toast must be visually above modal content')
assert(css.includes('.harmony-modal-feedback-card'), 'Toast must have shared styling')
assert(css.includes('html[data-harmony-theme="dark"] .harmony-modal-feedback-error'), 'Dark theme support')
assert(css.includes('body[data-harmony-feedback-relayed="true"]'), 'Background duplicate should be suppressed')
assert(css.includes('max-width: calc(100vw - 32px)'), 'Mobile overflow guard')
console.log('PASS: RC2E global modal feedback bridge, accessible modal layer, observer, dismissal and theme guards.')
