import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const leave = read('app/employee/leave/page.tsx')
const phl = read('app/employee/phl/page.tsx')
const css = read('app/harmony-rc3a-light-refinement.css')
const start = leave.indexOf('function HistorySection(')
const end = leave.indexOf('function HistoryCard(', start)
assert(start >= 0 && end > start, 'Existing HistorySection must remain present')
const cards = leave.slice(start, end)
assert.match(cards, /harmony-leave-history-grid/, 'Three-card grid must be present')
assert.match(cards, /xl:grid-cols-\[minmax\(0,1\.35fr\)_minmax\(0,1fr\)_minmax\(0,1fr\)\]/, 'Desktop must have three columns')
assert.match(cards, /Riwayat Pengajuan Cuti \/ Izin \/ PHL/)
assert.match(cards, /Saldo PHL Aktif/)
assert.match(cards, /Pengajuan Saldo PHL/)
assert.equal((cards.match(/harmony-card/g) ?? []).length, 3, 'Must have three independent cards')
assert.match(cards, /href="\/employee\/phl"/, 'Balance request CTA must use existing dedicated route')
assert.match(cards, /Buka form Pengajuan Saldo PHL/, 'CTA must be labeled accessibly')
assert.match(cards, /Minimal 4 jam penugasan/)
assert.match(cards, /Surat Tugas atau evidence/)
assert.match(cards, /90 hari/)
assert.match(css, /harmony-leave-phl-request-card/)
assert.match(css, /focus-visible/)
assert.match(phl, /submitPHLWorkRequest\(/, 'Existing dedicated PHL workflow must remain intact')
assert(existsSync(new URL('../app/employee/phl/page.tsx', import.meta.url)), 'Dedicated route must exist')
console.log('RC3B PASS — three independent responsive cards, existing PHL balance-request route, preserved leave workflow')
