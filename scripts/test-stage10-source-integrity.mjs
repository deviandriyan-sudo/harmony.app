import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
const read = p => readFileSync(p,'utf8')
const toggle = read('components/theme/ThemeToggle.tsx')
const css = read('app/globals.css')
const layout = read('app/layout.tsx')
const pkg = JSON.parse(read('package.json'))
const lock = JSON.parse(read('package-lock.json'))
assert.equal(pkg.version, lock.version, 'package and lock versions must agree')
assert.match(toggle, /<Moon size=\{18\}/)
assert.match(toggle, /<Sun size=\{18\}/)
assert.doesNotMatch(toggle, />Gelap<|>Terang<|harmony-theme-label/, 'Theme label still visible')
assert.match(toggle, /aria-label="Aktifkan mode gelap"/)
assert.match(toggle, /aria-label="Aktifkan mode terang"/)
assert.match(toggle, /aria-pressed=/)
assert.match(css, /\.harmony-theme-switch button:focus-visible/)
assert.match(css, /width:40px;height:40px/)
assert.doesNotMatch(css, /\.harmony-theme-label/)
assert.match(layout, /HarmonyThemeProvider/)
assert.match(read('components/layout/AppSidebar.tsx'), /HarmonyThemeToggle/)
assert.match(read('app/login/page.tsx'), /HarmonyThemeToggle/)
assert.match(read('lib/remed-session-client.ts'), /cachedToken !== token/)
assert.match(read('app/api/remed/dashboard/route.ts'), /count: 'exact', head: true/)
assert.match(read('app/api/cron/leave-lifecycle/route.ts'), /HARMONY_LEAVE_CRON_ENABLED/)
const walk = d => readdirSync(d,{withFileTypes:true}).flatMap(x=>x.isDirectory()?walk(join(d,x.name)):[join(d,x.name)])
assert.equal(walk('app').filter(x=>x.replaceAll('\\','/').endsWith('/page.tsx')).length,64)
assert.equal(walk('app/api').filter(x=>x.replaceAll('\\','/').endsWith('/route.ts')).length,49)
// Generated caches and .env.local may legitimately exist after local installation; verify ZIP exclusions during packaging instead.
console.log('Stage 10 source checks PASS: icon-only theme, persisted provider, Stage 9 guards, Stage 8 cron, 113 routes, compact source')
