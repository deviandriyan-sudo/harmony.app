import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
const args=process.argv.slice(2)
const index=args.indexOf('--package-root')
const root = index < 0 ? path.resolve(fileURLToPath(new URL('../../',import.meta.url))) : path.resolve(args[index+1]||'')
const dir=path.join(root,'02_DATABASE_SQL','RC2I_CONTROLLED_APPLY')
const read=(p)=>{ const f=path.join(dir,p); assert.ok(existsSync(f),`Missing SQL: ${f}`); return readFileSync(f,'utf8') }
const pre=read('00_RC2I_PRECHECK_READ_ONLY.sql')
const migration=read('01_RC2I_TRANSACTIONAL_WORKFLOW_REVIEW_BEFORE_APPLY.sql')
const rollback=read('99_RC2I_ROLLBACK_MANUAL_REVIEW.sql')
const post=read('02_RC2I_POSTCHECK_READ_ONLY.sql')
const access=read('03_OPTIONAL_REVOKE_ANON_FIVE_TABLES_REVIEW_FIRST.sql')
assert.match(migration,/^BEGIN;[\s\S]*?COMMIT;\s*$/m)
assert.match(migration,/SET LOCAL lock_timeout = '5s'/)
assert.match(migration,/RC2I BLOCKED: baseline mismatch:/)
assert.match(migration,/harmony_guard_leave_hr_decision_v1_trg/)
assert.match(migration,/hr_reject_leave_request_atomic_rc2i/)
assert.match(migration,/PERFORM pg_advisory_xact_lock\(hashtext\(v_request.employee_id::text\)\)/i)
assert.match(migration,/rollback_employee_annual_leave_usage/)
assert.match(migration,/rollback_employee_phl_usage/)
assert.match(migration,/hr_status.*approved/i)
assert.match(migration,/annual_leave_balance = v_balance_after/i)
assert.match(migration,/status = 'rejected', hr_status = 'rejected'/i)
assert.match(migration,/REVOKE ALL ON FUNCTION public.hr_reject_leave_request_atomic_rc2i/i)
assert.match(access,/REVOKE ALL PRIVILEGES ON TABLE/i)
assert.match(access,/ANON ACCESS STILL PRESENT/i)
assert.match(post,/FROM public.leave_requests lr/)
assert.equal((pre.match(/'public\.[a-z0-9_]+\([^']*\)'/g)||[]).length,9)
assert.equal((rollback.match(/CREATE OR REPLACE FUNCTION public\./g)||[]).length,9)
assert.equal((migration.match(/CREATE OR REPLACE FUNCTION public\./g)||[]).length,10)
assert.equal((migration.match(/AS \$function\$/g)||[]).length,10)
assert.equal((migration.match(/\$function\$/g)||[]).length,20)
// PostgreSQL requires a statement terminator after each CREATE FUNCTION body.
assert.equal((migration.match(/^\$function\$;$/gm)||[]).length,10, 'Migration must terminate every CREATE FUNCTION with $function$;')
assert.equal((rollback.match(/^\$function\$;$/gm)||[]).length,9, 'Rollback must terminate every CREATE FUNCTION with $function$;')
assert.doesNotMatch(migration,/^\$function\$$/m,'Missing SQL semicolon after migration function body')
assert.doesNotMatch(rollback,/^\$function\$$/m,'Missing SQL semicolon after rollback function body')
assert.doesNotMatch(migration,/\b(?:DROP TABLE|TRUNCATE|DELETE FROM public\.)\b/i)
assert.doesNotMatch(migration,/\b(?:ALTER TABLE.*ENABLE ROW LEVEL SECURITY|UPDATE public\.annual_leave_cycles)\b/i)
console.log('RC2I SQL artifact static PASS (10 function definitions, 9 fingerprint guards, rollback, no table/data migration).')
console.log('NOT RUN: PostgreSQL syntax, trigger behavior, transaction E2E, Supabase grants/RLS integration.')
