/* eslint-disable @typescript-eslint/no-require-imports -- Node regression test */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
const vm = require('node:vm')
const code = fs.readFileSync('lib/phl-work-expiry.ts','utf8')
const output = ts.transpileModule(code,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText
const mod={exports:{}}
vm.runInNewContext(output,{module:mod,exports:mod.exports,Date},{filename:'phl-work-expiry.js'})
const {phlWorkExpiryDate: expiry,phlWorkApprovalExpired: isExpired} = mod.exports
assert.equal(expiry('2026-08-22'),'2026-11-20')
assert.equal(isExpired('2026-08-22','2026-11-20'),false,'Last eligible day inclusive per SQL')
assert.equal(isExpired('2026-08-22','2026-11-21'),true,'SQL expiry uses strict less-than')
assert.equal(isExpired('2026-08-09','2026-11-20'),true,'Legacy August PHL is no longer eligible')
assert.equal(isExpired('2026-05-14','2026-11-20'),true,'Legacy May PHL is no longer eligible')
assert.equal(isExpired('2026-11-20','2026-11-20'),false)
assert.equal(expiry('2026-02-30'),null)
assert.equal(expiry('2024-02-29'),'2024-05-29')
assert.equal(expiry(''),null)
const page=fs.readFileSync('components/employee/TodayTeamAvailability.tsx','utf8')
assert.match(page,/md:grid-cols-2 xl:grid-cols-3/)
assert.match(page,/Object\.keys\(categoryMeta\)/)
assert.match(page,/category=\{category\}/)
assert.match(page,/items=\{grouped\[category\]\}/)
assert.doesNotMatch(page,/setActiveCategory|activeCategory===/)
const dashboard=fs.readFileSync('app/employee/dashboard/page.tsx','utf8')
assert.match(dashboard,/<TodayTeamAvailability\s*\/>/)
const supervisor=fs.readFileSync('app/employee/approvals/page.tsx','utf8')
assert.match(supervisor,/Approval Tim/)
const api=fs.readFileSync('app/api/phl/work-requests/[id]/review/route.ts','utf8')
const guard=api.indexOf("decision === 'approve' && phlWorkApprovalExpired(clean(target.work_date))")
const sync=api.indexOf('const synced = await syncApprovedPHLToAttendance(')
const rpc=api.indexOf("'harmony_review_phl_work_request_v1'")
assert(guard>0 && sync>guard && rpc>guard,'90 day guard must run before attendance writes and RPC')
assert.match(api,/decision === 'approve'/)
assert.match(api,/PHL_EXPIRED/)
const phlPage=fs.readFileSync('app/employee/approvals/phl/page.tsx','utf8')
assert.match(phlPage,/disabled=\{processing === item\.id \|\| phlWorkApprovalExpired\(item\.work_date\)\}/)
assert.match(phlPage,/decision === 'approve' && phlWorkApprovalExpired/)
assert.match(phlPage,/Masa berlaku PHL berakhir/)
assert.match(phlPage,/onClick=\{\(\) => void decide\(item, 'reject'\)\}/)
console.log('RC2P dashboard & PHL expiry PASS: three separate employee categories, supervisor workflow preserved, UTC 90-day boundaries, server pre-write guard, expired approval disabled, rejection retained')
