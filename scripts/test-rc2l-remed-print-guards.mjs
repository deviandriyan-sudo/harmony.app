import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = name => readFileSync(name, 'utf8')
const link = read('components/remed/RemedPrintLink.tsx')
assert.match(link, /href=\{`\/remed\/\$\{role\}\/claims\/\$\{encodeURIComponent\(claimId\)\}\/print`\}/)
assert.match(link, /target="_blank"/)
assert.match(link, /noopener noreferrer/)
assert.match(read('components/remed/ClaimAdminActions.tsx'), /<RemedPrintLink claimId=\{claim\.id\} role=\{role\}/)
const queue = read('components/remed/RemedAdminQueue.tsx')
assert.match(queue, /<RemedPrintLink claimId=\{claim\.id\} role=\{mode === 'hr_review' \? 'hr' : 'finance'\}/)
for (const mode of ['hr_review', 'finance_review', 'payment']) assert.match(queue, new RegExp(mode))
assert.match(read('components/remed/RemedHistoryWorkspace.tsx'), /printRole=\{role\}/)
const history = read('components/remed/RemedProcessHistory.tsx')
assert.match(history, /printRole && !item\.is_deleted && item\.claim_id/)
const api = read('app/api/remed/claims/[id]/route.ts')
assert.match(api, /requireRemedApi\(request\)/)
assert.match(api, /ctx\.access\.role === 'employee' && data\.employee_id !== ctx\.access\.employee_id/)
assert.match(api, /from\('employees'\)/)
assert.match(api, /from\('remed_claim_types'\)/)
assert.doesNotMatch(api, /enrichRemedClaims/, 'Print API must not depend on unrelated entitlement/attachment joins')
assert.match(api, /signature_warning: signatureWarning/)
const form = read('components/remed/PaymentRequestPrint.tsx')
assert.match(form, /Form pembayaran Re-Med belum dapat ditampilkan/)
assert.match(form, /Coba Lagi/)
assert.match(form, /dataWarning/)
assert.match(form, /window\.print\(\)/)
for (const role of ['hr', 'finance']) assert.match(read(`app/remed/${role}/claims/[id]/print/page.tsx`), /PaymentRequestPrint/)
console.log('RC2L Re-Med print guard PASS — HR/Finance dashboard, queues, payment, history, auth, partial data, retry & print routes (static).')
